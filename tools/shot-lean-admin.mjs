import { chromium } from "playwright-core";
const BASE = process.env.BASE || "http://127.0.0.1:8788";
const OUT = "../docs/screenshots-lean";
const b = await chromium.launch({ executablePath: "C:/Program Files/Google/Chrome/Application/chrome.exe", headless: true, args: ["--no-sandbox"] });
const ctx = await b.newContext({ viewport: { width: 1512, height: 950 }, deviceScaleFactor: 1.5, locale: "zh-CN" });
const p = await ctx.newPage();
const errs = []; p.on("pageerror", e => errs.push(String(e)));
await p.goto(`${BASE}/login`, { waitUntil: "networkidle" });
await p.fill("#u", "admin"); await p.fill("#p", "admin123"); await p.click("#go");
await p.waitForURL("**/app"); await p.goto(`${BASE}/admin`, { waitUntil: "networkidle" });
await p.waitForTimeout(1200);
await p.screenshot({ path: `${OUT}/36-admin-overview.png` });
await p.click('.nav[data-tab="data"]'); await p.waitForTimeout(900);
await p.click("#pv-go"); await p.waitForTimeout(1200);
await p.screenshot({ path: `${OUT}/38-admin-sql-preview.png` });
await p.click('.nav[data-tab="audit"]'); await p.waitForTimeout(700);
await p.screenshot({ path: `${OUT}/39-admin-audit.png` });
console.log("errors", errs.length ? errs : "none");
await b.close();
